import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { articles, tags, techStack } from '../database/content.mjs';

const outputPath = fileURLToPath(new URL('../database/seed.sql', import.meta.url));

function sql(value) {
    if (value === null || value === undefined) return 'NULL';
    return `'${String(value).split('\\').join('\\\\').split("'").join("''")}'`;
}

function tuple(values) {
    return `(${values.join(', ')})`;
}

const tagIds = new Map(tags.map((tag, index) => [tag.name, index + 1]));
const techIds = new Map(techStack.map((tech, index) => [tech.name, index + 1]));

for (const article of articles) {
    for (const tag of article.tags) {
        if (!tagIds.has(tag)) throw new Error(`Unknown tag "${tag}" in article ${article.id}`);
    }
    for (const tech of article.tech) {
        if (!techIds.has(tech)) throw new Error(`Unknown tech "${tech}" in article ${article.id}`);
    }
}

const articleRows = articles.map((article) =>
    tuple([
        article.id,
        sql(article.title),
        sql(article.description),
        sql(article.content),
        sql(article.icon),
        1,
        0,
        0,
        sql('published'),
        sql(article.createdAt),
        sql(article.updatedAt),
        sql(article.publishedAt)
    ])
);

const articleTagRows = articles.flatMap((article) => article.tags.map((tag) => tuple([article.id, tagIds.get(tag)])));

const articleTechRows = articles.flatMap((article) => article.tech.map((tech) => tuple([article.id, techIds.get(tech)])));

const lines = [
    '-- Generated by `pnpm content:seed`. Edit database/content.mjs instead.',
    '-- The public content is anonymized and based on the owner-provided work history.',
    'SET NAMES utf8mb4;',
    'USE blog;',
    '',
    '-- A non-administrator author used only to own seeded public articles.',
    'INSERT INTO users (id, username, email, password_hash, display_name, role) VALUES',
    tuple([1, sql('content-owner'), sql('content-owner@localhost.invalid'), sql('$2b$12$3zMvMknpMR2YvnG1H9Tpy.ImcqawKAmssEOOnAJsFIAXA6d293eKC'), sql('Content Owner'), sql('viewer')]) + ';',
    '',
    'INSERT INTO tags (id, name, slug, color, icon, description) VALUES',
    tags.map((tag, index) => tuple([index + 1, sql(tag.name), sql(tag.slug), sql(tag.color), sql(tag.icon), sql(tag.description)])).join(',\n') + ';',
    '',
    'INSERT INTO tech_stack (id, name, icon, link, description) VALUES',
    techStack.map((tech, index) => tuple([index + 1, sql(tech.name), sql(tech.icon), sql(tech.link), sql(tech.description)])).join(',\n') + ';',
    '',
    'INSERT INTO articles',
    '    (id, title, description, content, cover_image, author_id, view_count, star_count, status, created_at, updated_at, published_at)',
    'VALUES',
    articleRows.join(',\n') + ';',
    '',
    'INSERT INTO article_tags (article_id, tag_id) VALUES',
    articleTagRows.join(',\n') + ';',
    '',
    'INSERT INTO article_tech_stack (article_id, tech_id) VALUES',
    articleTechRows.join(',\n') + ';',
    ''
];

await writeFile(outputPath, lines.join('\n'), 'utf8');
console.log(`Generated ${articles.length} articles in ${outputPath}`);
